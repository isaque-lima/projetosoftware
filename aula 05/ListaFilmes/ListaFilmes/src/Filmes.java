package Entidades;

public class Filmes {

    private String titulo;
    private String genero;
    private int duracao;
    private double preco;


    public Filmes(String titulo, String genero, int duracao, double preco) {
        this.titulo = titulo;
        this.genero = genero;
        this.duracao = duracao;
        this.preco = preco;
    }
}
